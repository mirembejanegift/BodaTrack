"""Django admin registration for day-to-day staff use and corrections."""
from django.contrib import admin

from .models import (
    AuditLog,
    Motorcycle,
    OwnershipAgreement,
    Payment,
    PaymentAllocation,
    Rider,
    WeeklyInstalment,
)


@admin.register(Rider)
class RiderAdmin(admin.ModelAdmin):
    list_display = ("id", "full_name", "phone_number", "is_active")
    search_fields = ("full_name", "phone_number")
    list_filter = ("is_active",)


@admin.register(Motorcycle)
class MotorcycleAdmin(admin.ModelAdmin):
    list_display = ("id", "registration_number", "make_model", "is_active")
    search_fields = ("registration_number", "make_model")
    list_filter = ("is_active",)


class InstalmentInline(admin.TabularInline):
    model = WeeklyInstalment
    extra = 0
    fields = ("due_date", "amount_due", "status")
    readonly_fields = ("due_date", "amount_due", "status")

    def has_add_permission(self, request, obj=None):
        return False  # schedules are generated by services.generate_instalments

    def has_change_permission(self, request, obj=None):
        return False


@admin.register(OwnershipAgreement)
class OwnershipAgreementAdmin(admin.ModelAdmin):
    list_display = ("id", "rider", "motorcycle", "total_price", "weekly_amount",
                    "start_date", "status", "legal_transfer_approved_at")
    list_filter = ("status",)
    search_fields = ("rider__full_name", "motorcycle__registration_number")
    inlines = [InstalmentInline]


@admin.register(WeeklyInstalment)
class WeeklyInstalmentAdmin(admin.ModelAdmin):
    list_display = ("id", "agreement", "due_date", "amount_due", "status")
    list_filter = ("status",)
    search_fields = ("agreement__rider__full_name", "agreement__motorcycle__registration_number")


@admin.register(Payment)
class PaymentAdmin(admin.ModelAdmin):
    list_display = ("id", "receipt_number", "agreement", "amount", "method", "status", "paid_at")
    list_filter = ("status", "method")
    search_fields = ("receipt_number", "reference", "agreement__rider__full_name")
    readonly_fields = ("reversed_at", "reversal_reason", "created_at")

    # Payments can never be edited or deleted through the admin; corrections
    # must go through the reversal service so the audit trail stays honest.
    def has_change_permission(self, request, obj=None):
        return request.user.is_superuser

    def has_delete_permission(self, request, obj=None):
        return False


@admin.register(PaymentAllocation)
class PaymentAllocationAdmin(admin.ModelAdmin):
    list_display = ("id", "payment", "instalment", "amount")
    readonly_fields = ("payment", "instalment", "amount")

    def has_add_permission(self, request):
        return False

    def has_change_permission(self, request, obj=None):
        return False

    def has_delete_permission(self, request, obj=None):
        return False


@admin.register(AuditLog)
class AuditLogAdmin(admin.ModelAdmin):
    list_display = ("id", "created_at", "action", "entity_type", "entity_id", "actor")
    list_filter = ("action", "entity_type")
    search_fields = ("action", "entity_type", "reason")

    def has_add_permission(self, request):
        return False

    def has_change_permission(self, request, obj=None):
        return False

    def has_delete_permission(self, request, obj=None):
        return False
